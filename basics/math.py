
# Module 1: Math Operations
friends = 0
friends += 2 # friends = friends + 2 ( you can use all operators like +, -, *, /, %, **, //, etc. )
print(f"You have {friends} friends.") # You have 2 friends.

# Module 2: Round a number
aNumber = 2.55
aNumber = round(aNumber)
print(f"The rounded number is {aNumber}.") # The rounded number is 3.

# Module 3: Absolute value
anotherNumber = -4
anotherNumber = abs(anotherNumber)
print(f"The absolute value of the number is {anotherNumber}.") # The absolute value of the number is 4.

# Module 4: Maximum value
maxNumber = max(2, 5, 8, 1)
print(f"The maximum value is {maxNumber}.") # The maximum value is 8.

#Module 5: Minimum value
minNumber = min(2, 5, 8, 1)
print(f"The minimum value is {minNumber}.") # The minimum value is 1.

# Module 6: Pi
import math
piValue = math.pi
print(f"The value of pi is {piValue}.") # The value of pi is 3.141592653589793.

# Module 7: Square root
sqrtValue = math.sqrt(16)
print(f"The square root of 16 is {sqrtValue}.") # The square root of 16 is 4.0.

# Module 8: Power
powerValue = math.pow(2, 3)
print(f"The power of 2 to the 3rd is {powerValue}.") # The power of 2 to the 3rd is 8.0.    

